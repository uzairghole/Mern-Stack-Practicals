// Write programs using loops and template literals
let student = "Uzair";

// Template Literal
console.log(`Welcome ${student}`);

// For Loop
console.log("For Loop");

for (let i = 1; i <= 5; i++) {
    console.log(`Number: ${i}`);
}

// While Loop
console.log("While Loop");

let j = 1;
while (j <= 5) {
    console.log(`Value: ${j}`);
    j++;
}